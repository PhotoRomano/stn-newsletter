#!/usr/bin/env python3
"""
Regenerate business_owner_map.json straight from the master draft, instead
of hand-maintaining it as a separate sidecar file that can itself drift
from what the newsletter actually says.

    python3 extract_business_owner_map.py drafts/2026-10-29.both.html

Reads every `<li data-slug="...">` inside the English column
(`<td class="bl-col bl-en">`) of the Parishioner Businesses section --
the `<strong>` text inside each is the owner name. Only the English
column is read (proper nouns are identical in both languages by
convention; see check_links.py's docstring for the broader "names stay
in Latin script in both columns" rule), so there's exactly one entry per
slug regardless of how many languages carry the same `data-slug`.

Writes the result to business_owner_map.json, preserving the leading
`_comment` key. Run this after editing the Parishioner Businesses
section in drafts/<date>.both.html -- wired into build.py so it happens
automatically on every `python3 build.py drafts/<date>.both.html` run,
but can be run standalone too.

Exits non-zero (without writing) if any `data-slug` has no `<strong>`
child or an empty one -- a malformed listing is worse silently ignored
than written as a blank map entry.
"""
import json
import sys
from pathlib import Path

from bs4 import BeautifulSoup

ROOT = Path(__file__).parent
MAP_PATH = ROOT / "business_owner_map.json"

MAP_COMMENT = (
    "AUTO-GENERATED by extract_business_owner_map.py from the Parishioner "
    "Businesses section's data-slug attributes in the current week's "
    "drafts/<date>.both.html -- do not hand-edit, it will be overwritten "
    "on the next `python3 build.py` run. To change an owner name, edit "
    "the <li data-slug=...> in the master draft instead. "
    "check_business_owner_sync.py diffs this against the live businesses "
    "D1 table's contact_name."
)


def extract(master_path):
    soup = BeautifulSoup(master_path.read_text(encoding="utf-8"), "html.parser")
    owner_map = {}
    errors = []

    for col in soup.select("td.bl-col.bl-en"):
        for li in col.select("li[data-slug]"):
            slug = li["data-slug"]
            strong = li.find("strong")
            name = strong.get_text(strip=True) if strong else ""
            if not name:
                errors.append(f"slug={slug!r} has no non-empty <strong> owner name")
                continue
            owner_map[slug] = name

    return owner_map, errors


def write_map(owner_map):
    output = {"_comment": MAP_COMMENT, **owner_map}
    MAP_PATH.write_text(json.dumps(output, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    master_path = Path(sys.argv[1])

    owner_map, errors = extract(master_path)

    if errors:
        print(f"FAILED -- {len(errors)} issue(s), not writing {MAP_PATH.name}:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)

    if not owner_map:
        print(f"FAILED -- no data-slug <li> entries found in {master_path} -- "
              f"did the Parishioner Businesses section lose its data-slug attributes?")
        sys.exit(1)

    write_map(owner_map)
    print(f"wrote {MAP_PATH.name} ({len(owner_map)} businesses, from {master_path})")


if __name__ == "__main__":
    main()
