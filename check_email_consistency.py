#!/usr/bin/env python3
"""
Catch drift between the hand-maintained email brief and the board-approved
full issue before the Beehiiv draft is loaded.

    python3 check_email_consistency.py 2026-10-08

Why this exists: `<date>.email.html` is written by hand, separately from
`<date>.both.html` -- it is NOT generated by build.py, so a correction
made to both.html during board review (a renamed event, a fixed date)
has no mechanism to propagate to the email brief. This bit for real on
2026-10-08: the board corrected the Serbia election date (Oct 24 -> 25)
and the St. George retreat's Serbian name ("Јесењи реколект" -> "Јесење
духовно сабрање") in both.html, but email.html still had both stale
values when it was loaded into the Beehiiv draft -- caught only because
the draft was read closely during that step, not because anything
flagged it automatically.

Two checks, against the VISIBLE TEXT only (HTML tags/attributes stripped,
so a UTM-tagged href doesn't trip the word check):

  1. DATE NUMBERS (hard failure) -- every (month, day) mentioned in
     email.html (English "Mon Day" or Serbian "Day. mon") must also
     appear somewhere in both.html. A date in the brief that doesn't
     exist anywhere in the approved full issue is almost certainly stale.
     Covers all 12 months, English + Serbian, full name or common
     abbreviation, nominative or genitive Serbian case -- originally
     hardcoded to October only (the month of the 2026-10-08 incident
     above), generalized 2026-11-02 after a November issue's stale date
     sailed through undetected during testing. Tracks month WITH day (not
     bare day numbers) specifically to avoid a false negative across
     month boundaries -- e.g. "Oct 15" approved in both.html must not
     silently cover a stale "15. нов" in email.html just because the
     digits match.

  2. STALE WORDS (soft warning, not a failure) -- any Cyrillic or Latin
     word of 5+ characters in email.html that does not appear anywhere
     in both.html at all. This is advisory, not a hard gate: email.html
     legitimately condenses/rephrases things, so some unique vocabulary
     is expected (its own Special Assembly callout, footer boilerplate,
     etc.) -- but a flagged word is worth a human glance before sending,
     since it's exactly the shape of signal that caught the retreat
     rename. Pass --strict to make this a hard failure too.

Run this BEFORE loading the Beehiiv draft (README Step 5), right after
add_utm_tags.py.

Also runs automatically, WARN-ONLY, from hooks/pre-commit whenever a
drafts/<date>.both.html OR drafts/<date>.email.html is staged -- so a
mid-week correction to the master (the exact 2026-10-08 incident above)
gets flagged at commit time instead of only at the final Thursday
publish pass, days later. check(date) is the importable entry point the
hook uses (returns (problems, warnings) lists, never exits); main() is
the CLI wrapper that turns the same result into exit codes.
"""
import re
import sys
from pathlib import Path

from bs4 import BeautifulSoup

from check_utils import CheckError, require_files

# Canonical month key -> (English stem regex, Serbian stem regex). Stems
# are deliberately permissive (a short literal prefix + a trailing
# cyrillic/letter class) rather than an exhaustive enumeration of every
# inflected form, since real usage in these drafts mixes nominative
# ("1. октобар") and genitive ("11. октобра") case inconsistently, plus
# both 3-letter and full-word abbreviations on the English side ("Aug"
# and "August" both appear). Safe to be loose here because each stem is
# only matched when directly adjacent to a date-shaped number in the
# patterns below, not matched against free-standing prose.
MONTHS = {
    "jan": (r"Jan(?:uary)?\.?", r"јан[а-шa-z]*"),
    "feb": (r"Feb(?:ruary)?\.?", r"феб[а-шa-z]*"),
    "mar": (r"Mar(?:ch)?\.?", r"мар[а-шa-z]*"),
    "apr": (r"Apr(?:il)?\.?", r"апр[а-шa-z]*"),
    "may": (r"May", r"маја?"),
    "jun": (r"Jun(?:e)?\.?", r"јуна?"),
    "jul": (r"Jul(?:y)?\.?", r"јула?"),
    "aug": (r"Aug(?:ust)?\.?", r"авг[а-шa-z]*"),
    "sep": (r"Sep(?:t(?:ember)?)?\.?", r"сеп[а-шa-z]*"),
    "oct": (r"Oct(?:ober)?\.?", r"окт[а-шa-z]*"),
    "nov": (r"Nov(?:ember)?\.?", r"нов[а-шa-z]*"),
    "dec": (r"Dec(?:ember)?\.?", r"дец[а-шa-z]*"),
}

# (month_key, compiled_pattern) pairs -- English "Mon Day", Serbian "Day. mon".
DATE_PATTERNS = []
for _key, (_en, _sr) in MONTHS.items():
    DATE_PATTERNS.append((_key, re.compile(_en + r"\s+(\d{1,2})\b")))
    DATE_PATTERNS.append((_key, re.compile(r"(\d{1,2})\.\s*" + _sr + r"\b", re.IGNORECASE)))


def find_dates(text):
    """Returns a set of (month_key, day) tuples found in text."""
    found = set()
    for month_key, pattern in DATE_PATTERNS:
        for day in pattern.findall(text):
            found.add((month_key, int(day)))
    return found

WORD_PATTERN = re.compile(r"[A-Za-zА-Яа-яЂђЋћЧчЏџШшЖжЉљЊњ]{5,}")

# Visible-text words that legitimately appear only in the email brief --
# not a sign of staleness, just the brief's own framing/boilerplate.
KNOWN_EMAIL_ONLY = {
    "issue", "brief", "week's", "Messenger", "This", "about", "Church",
    "Serbian", "Orthodox", "Nicholas", "Elkins", "Stahr", "receiving",
    "family", "preferences", "Unsubscribe", "Update", "powered", "beehiiv",
}


URL_PATTERN = re.compile(r"https?://\S+")


def visible_text(path):
    soup = BeautifulSoup(path.read_text(encoding="utf-8"), "html.parser")
    for tag in soup(["style", "script"]):
        tag.decompose()
    # strip URLs shown as literal link text (e.g. a fallback "https://..."
    # line under a button) -- those aren't prose, they're link targets.
    return URL_PATTERN.sub(" ", soup.get_text(" "))


def check(date, strict=False):
    """Returns (problems, warnings) -- both lists of strings, either may be
    empty. Raises CheckError on a fatal precondition failure (missing file).
    Never exits; never prints. main() is the CLI wrapper for that."""
    both_path = Path(f"drafts/{date}.both.html")
    email_path = Path(f"drafts/{date}.email.html")
    require_files(both_path, email_path)

    both_text = visible_text(both_path)
    email_text = visible_text(email_path)

    problems = []
    warnings = []

    # 1. Date numbers (month + day together, not bare day numbers)
    both_dates = find_dates(both_text)
    email_dates = find_dates(email_text)
    stale_dates = email_dates - both_dates
    if stale_dates:
        stale_labels = sorted(f"{m}-{d}" for m, d in stale_dates)
        approved_labels = sorted(f"{m}-{d}" for m, d in both_dates)
        problems.append(
            f"email.html mentions date(s) {stale_labels} "
            f"that don't appear anywhere in both.html (approved dates: {approved_labels}) "
            f"-- likely a stale date left over from before a board correction"
        )

    # 2. Stale words
    both_words = set(WORD_PATTERN.findall(both_text))
    email_words = set(WORD_PATTERN.findall(email_text))
    stale_words = sorted(email_words - both_words - KNOWN_EMAIL_ONLY)
    if stale_words:
        msg = f"word(s) in email.html not found anywhere in both.html: {stale_words}"
        if strict:
            problems.append(msg)
        else:
            warnings.append(msg)

    return problems, warnings


def main():
    args = sys.argv[1:]
    strict = "--strict" in args
    args = [a for a in args if a != "--strict"]
    if len(args) != 1:
        print(__doc__)
        sys.exit(1)
    date = args[0]

    try:
        problems, warnings = check(date, strict=strict)
    except CheckError as e:
        print(str(e))
        sys.exit(1)

    if warnings:
        print(f"WARNINGS -- {len(warnings)} (advisory, review before sending):")
        for w in warnings:
            print(f"  - {w}")

    if problems:
        print(f"\nFAILED -- {len(problems)} issue(s):")
        for p in problems:
            print(f"  - {p}")
        sys.exit(1)

    print(f"\nOK -- drafts/{date}.email.html is consistent with drafts/{date}.both.html"
          + (" (no warnings)" if not warnings else ""))


if __name__ == "__main__":
    main()
