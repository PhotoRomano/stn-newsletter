#!/usr/bin/env python3
"""
Catch a stale <title> date left over from copy-pasting last week's file as
this week's starting template.

    python3 check_title_date.py 2026-10-15

Why this exists: `<date>.both.html` and `<date>.email.html` are both
hand-written/hand-copied (never generated by build.py), so nothing forces
their <title> tag's date to match the filename date. This bit for real on
2026-10-15 -- both files' <title> still read "Week of October 8, 2026"
after being copied from the 10-08 issue, even though the body content had
already been updated for the 15th. It's invisible in the rendered page
(titles aren't shown in the body) but it's exactly what link-preview
unfurlers (iMessage, Slack, etc.) show when someone pastes the URL, so the
board/subscribers saw the wrong week in the preview card.

(`.other.html` / `.serbian.html` are NOT checked here -- build.py
regenerates their <title> fresh from the date argument every time, so they
can't go stale this way. `.site.html` has no <title> at all.)

HARD GATE: run this BEFORE build.py (README Step 1, before Step "Fast
path"/prepare_publish.py's step 1) so a stale template title is caught
before it ships, not after.
"""
import re
import sys
from datetime import datetime
from pathlib import Path

EN_MONTHS = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]
# Nominative form, matching this repo's existing title convention
# (see drafts/2026-10-08.serbian.html / 2026-10-01.serbian.html).
SR_MONTHS_NOM = [
    "јануар", "фебруар", "март", "април", "мај", "јун",
    "јул", "август", "септембар", "октобар", "новембар", "децембар",
]

EN_DATE_PATTERN = re.compile(r"\b([A-Z][a-z]+)\s+(\d{1,2}),\s*(\d{4})\b")
SR_DATE_PATTERN = re.compile(r"\b(\d{1,2})\.\s*([А-Яа-я]+)\s*(\d{4})\b")


def get_title(path):
    text = path.read_text(encoding="utf-8")
    m = re.search(r"<title>(.*?)</title>", text, re.S)
    return m.group(1) if m else None


def check_english(path, expected_month, day, year):
    title = get_title(path)
    if title is None:
        return [f"{path}: no <title> tag found"]
    found = EN_DATE_PATTERN.findall(title)
    if not found:
        return [f"{path}: <title> has no recognizable date -- {title!r}"]
    problems = []
    for month, d, y in found:
        if (month, int(d), y) != (expected_month, day, str(year)):
            problems.append(
                f"{path}: <title> says '{month} {d}, {y}' but this is the "
                f"{expected_month} {day}, {year} issue -- {title!r}"
            )
    return problems


def check_serbian(path, expected_month_nom, day, year):
    title = get_title(path)
    if title is None:
        return [f"{path}: no <title> tag found"]
    found = SR_DATE_PATTERN.findall(title)
    if not found:
        return [f"{path}: <title> has no recognizable date -- {title!r}"]
    problems = []
    for d, month, y in found:
        if (int(d), month.lower(), y) != (day, expected_month_nom, str(year)):
            problems.append(
                f"{path}: <title> says '{d}. {month} {y}' but this is the "
                f"{day}. {expected_month_nom} {year} issue -- {title!r}"
            )
    return problems


def main():
    args = sys.argv[1:]
    if len(args) != 1:
        print(__doc__)
        sys.exit(1)
    date_str = args[0]
    date = datetime.strptime(date_str, "%Y-%m-%d")
    month_en = EN_MONTHS[date.month - 1]
    month_sr = SR_MONTHS_NOM[date.month - 1]

    checks = [
        (Path(f"drafts/{date_str}.both.html"), "en"),
        (Path(f"drafts/{date_str}.email.html"), "en"),
    ]

    problems = []
    for path, lang in checks:
        if not path.exists():
            continue
        if lang == "en":
            problems += check_english(path, month_en, date.day, date.year)

    # both.html carries the Serbian half of the title too (bilingual page) --
    # check it the same way email.html's English half is checked.
    both_path = Path(f"drafts/{date_str}.both.html")
    if both_path.exists():
        title = get_title(both_path)
        if title and SR_DATE_PATTERN.search(title):
            problems += check_serbian(both_path, month_sr, date.day, date.year)

    if problems:
        print(f"FAILED -- {len(problems)} stale <title> date issue(s):")
        for p in problems:
            print(f"  - {p}")
        sys.exit(1)

    print(f"OK -- titles for {date_str} match the issue date")


if __name__ == "__main__":
    main()
